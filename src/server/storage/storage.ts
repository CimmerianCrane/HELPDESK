import { createHmac, timingSafeEqual } from 'node:crypto'
import { mkdir, writeFile } from 'node:fs/promises'
import path from 'node:path'
import { env } from '@/lib/env'

/**
 * Where photographs and signatures are kept.
 *
 * Two drivers, because the tests and the dev machine must not need a bucket:
 * `disk` writes under `STORAGE_DISK_PATH`, `supabase` uses Storage over its REST API. Both hand the
 * browser a short-lived URL and let it upload directly — Vercel caps a function request body at
 * 4.5 MB, and a site photograph compressed on the phone is already close to that.
 *
 * Only `disk` receives bytes through this app (the signed URL points at `/api/files/store`).
 * Supabase's own signed upload URL is used as issued.
 */

export interface SignedUpload {
  url: string
  method: 'PUT'
}

export interface StorageAdapter {
  signedUploadUrl(key: string, contentType: string): Promise<SignedUpload>
  signedDownloadUrl(key: string, expiresInSeconds?: number): Promise<string>
  /** Accepts bytes written by this app. Supabase uses it for server-side writes only. */
  put(key: string, bytes: Uint8Array, contentType: string): Promise<void>
}

export const UPLOAD_TTL_SECONDS = 15 * 60

/** Keys are generated by this app, never by a client. Refuse anything that could escape the root. */
export function isSafeStorageKey(key: string): boolean {
  return (
    /^[A-Za-z0-9][A-Za-z0-9/_.-]*$/.test(key) &&
    !key.split('/').some((segment) => segment === '..' || segment === '.')
  )
}

/**
 * Signs `<key>.<expiry>`. Exported with the secret as an argument so the signature can be tested
 * without a configured environment — the adapter supplies the real secret.
 */
export function signUploadToken(key: string, expiresAt: number, signingSecret: string): string {
  const signature = createHmac('sha256', signingSecret)
    .update(`${key}.${expiresAt}`)
    .digest('base64url')
  return `${expiresAt}.${signature}`
}

export function verifyUploadToken(
  key: string,
  token: string,
  signingSecret: string,
  now = Date.now(),
): boolean {
  const [expiryText, signature] = token.split('.')
  const expiresAt = Number(expiryText)
  if (!Number.isFinite(expiresAt) || expiresAt < now || !signature) return false

  const expected = createHmac('sha256', signingSecret)
    .update(`${key}.${expiryText}`)
    .digest('base64url')
  const actualBuffer = Buffer.from(signature)
  const expectedBuffer = Buffer.from(expected)
  return actualBuffer.length === expectedBuffer.length && timingSafeEqual(actualBuffer, expectedBuffer)
}

function signingSecret(): string {
  const value = env().AUTH_SECRET
  if (!value) throw new Error('AUTH_SECRET is required to sign file upload URLs.')
  return value
}

function diskPath(key: string): string {
  if (!isSafeStorageKey(key)) throw new Error('Invalid storage key.')
  const root = path.resolve(env().STORAGE_DISK_PATH)
  const full = path.resolve(root, key)
  if (!full.startsWith(`${root}${path.sep}`)) throw new Error('Invalid storage key.')
  return full
}

const diskAdapter: StorageAdapter = {
  async signedUploadUrl(key) {
    const expiresAt = Date.now() + UPLOAD_TTL_SECONDS * 1000
    const token = signUploadToken(key, expiresAt, signingSecret())
    return {
      // Relative on purpose: the URL works on localhost and behind a proxy without APP_BASE_URL.
      url: `/api/files/store?key=${encodeURIComponent(key)}&token=${encodeURIComponent(token)}`,
      method: 'PUT',
    }
  },

  async signedDownloadUrl() {
    // Downloading a stored photo is slice 9's PDF work; nothing in slice 8 reads one back.
    throw new Error('The disk adapter has no download URL yet.')
  },

  async put(key, bytes) {
    const full = diskPath(key)
    await mkdir(path.dirname(full), { recursive: true })
    await writeFile(full, bytes)
  },
}

function supabaseConfig(): { url: string; key: string; bucket: string } {
  const e = env()
  if (!e.SUPABASE_URL || !e.SUPABASE_SERVICE_ROLE_KEY) {
    throw new Error('SUPABASE_URL and SUPABASE_SERVICE_ROLE_KEY are required for the supabase driver.')
  }
  return { url: e.SUPABASE_URL, key: e.SUPABASE_SERVICE_ROLE_KEY, bucket: e.SUPABASE_STORAGE_BUCKET }
}

async function supabaseRequest(pathname: string, init: RequestInit = {}): Promise<Record<string, unknown>> {
  const config = supabaseConfig()
  const response = await fetch(`${config.url}/storage/v1${pathname}`, {
    ...init,
    headers: {
      apikey: config.key,
      Authorization: `Bearer ${config.key}`,
      'Content-Type': 'application/json',
      ...init.headers,
    },
  })
  if (!response.ok) {
    throw new Error(`Supabase Storage returned ${response.status}: ${await response.text()}`)
  }
  return (await response.json()) as Record<string, unknown>
}

function absoluteStorageUrl(url: string): string {
  if (/^https?:\/\//.test(url)) return url
  return `${supabaseConfig().url}/storage/v1${url.startsWith('/') ? '' : '/'}${url}`
}

const supabaseAdapter: StorageAdapter = {
  async signedUploadUrl(key) {
    const config = supabaseConfig()
    const data = await supabaseRequest(
      `/object/upload/sign/${config.bucket}/${key}`,
      { method: 'POST', body: '{}' },
    )
    const url = (data.url ?? data.signedUrl) as string | undefined
    if (!url) throw new Error('Supabase did not return a signed upload URL.')
    return { url: absoluteStorageUrl(url), method: 'PUT' }
  },

  async signedDownloadUrl(key, expiresInSeconds = UPLOAD_TTL_SECONDS) {
    const config = supabaseConfig()
    const data = await supabaseRequest(`/object/sign/${config.bucket}/${key}`, {
      method: 'POST',
      body: JSON.stringify({ expiresIn: expiresInSeconds }),
    })
    const url = (data.signedURL ?? data.signedUrl) as string | undefined
    if (!url) throw new Error('Supabase did not return a signed download URL.')
    return absoluteStorageUrl(url)
  },

  async put(key, bytes, contentType) {
    const config = supabaseConfig()
    const response = await fetch(`${config.url}/storage/v1/object/${config.bucket}/${key}`, {
      method: 'POST',
      headers: {
        apikey: config.key,
        Authorization: `Bearer ${config.key}`,
        'Content-Type': contentType,
      },
      // A copy, so the Blob owns an ordinary ArrayBuffer rather than a possibly shared one.
      body: new Blob([new Uint8Array(bytes).buffer as ArrayBuffer], { type: contentType }),
    })
    if (!response.ok) {
      throw new Error(`Supabase Storage returned ${response.status}: ${await response.text()}`)
    }
  },
}

export function storage(): StorageAdapter {
  return env().STORAGE_DRIVER === 'supabase' ? supabaseAdapter : diskAdapter
}
