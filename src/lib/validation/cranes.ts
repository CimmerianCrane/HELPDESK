import { z } from 'zod'

/**
 * Input schemas for cranes. The register is the spine of the business: every job, report,
 * certificate and reminder hangs off a crane, so the fields here are the ones a certificate or a
 * statutory examination actually cites.
 */

export const CRANE_TYPES = [
  'OVERHEAD',
  'GANTRY',
  'JIB',
  'MOBILE',
  'TOWER',
  'HOIST',
  'OTHER',
] as const

export const CRANE_STATUSES = ['IN_SERVICE', 'RESTRICTED', 'OUT_OF_SERVICE', 'DECOMMISSIONED'] as const

const optionalText = (max: number) =>
  z
    .string()
    .trim()
    .max(max, `Use ${max} characters or fewer.`)
    .optional()
    .transform((value) => (value ? value : null))

const requiredText = (max: number, message: string) =>
  z.string().trim().min(1, message).max(max, `Use ${max} characters or fewer.`)

/** SAFE WORKING LOAD. A crane without one cannot be certified, so it is required and must be positive. */
const swl = z.coerce
  .number({ invalid_type_error: 'Enter the safe working load in kilograms.' })
  .positive('The safe working load must be greater than zero.')
  .max(2_000_000, 'That is larger than any crane this register should hold.')

const optionalNumber = (max: number) =>
  z
    .union([z.literal(''), z.coerce.number().min(0).max(max)])
    .optional()
    .transform((value) => (value === '' || value === undefined ? null : value))

const year = z
  .union([z.literal(''), z.coerce.number().int().min(1800).max(2100)])
  .optional()
  .transform((value) => (value === '' || value === undefined ? null : value))

const ISO_DATE = /^\d{4}-\d{2}-\d{2}$/

/**
 * The calendar day as a UTC midnight, or null if the day does not exist.
 *
 * `new Date('2024-02-31T00:00:00Z')` does not fail — it rolls forward to 2 March. Round-tripping the
 * value back to `YYYY-MM-DD` is what catches a transposed or impossible date before it is recorded as
 * the day a crane was registered.
 */
function isoDateToUtc(value: string): Date | null {
  const date = new Date(`${value}T00:00:00Z`)
  if (Number.isNaN(date.getTime())) return null
  return date.toISOString().slice(0, 10) === value ? date : null
}

/** `YYYY-MM-DD` from a date input, stored as a UTC midnight so it prints as the same calendar day. */
const optionalDate = z
  .union([z.literal(''), z.string().regex(ISO_DATE, 'Use a date like 2026-10-26.')])
  .optional()
  .transform((value) => (value === '' || value === undefined ? null : value))
  .superRefine((value, ctx) => {
    if (value !== null && isoDateToUtc(value) === null) {
      ctx.addIssue({ code: z.ZodIssueCode.custom, message: 'That is not a real date.' })
    }
  })
  .transform((value) => (value === null ? null : isoDateToUtc(value)))

/**
 * `qrValue` and `assetTag` are generated by the service, not typed by a person — see
 * `server/cranes/qr.ts`. They are in the update schema only so the service can re-assert them.
 */
export const createCraneSchema = z.object({
  customerId: requiredText(40, 'A crane belongs to a customer.'),
  siteId: requiredText(40, 'A crane has to be at a site.'),
  assetTag: optionalText(60),
  qrValue: optionalText(120),
  type: z.enum(CRANE_TYPES, {
    errorMap: () => ({ message: 'Choose the type of crane.' }),
  }),
  brand: optionalText(80),
  model: optionalText(80),
  serialNumber: optionalText(120),
  swlKg: swl,
  yearOfManufacture: year,
  statutoryRegistrationNo: optionalText(80),
  registrationDate: optionalDate,
  ownerEntity: optionalText(160),
  locationOnSite: optionalText(160),
  hourMeter: optionalNumber(10_000_000),
  notes: optionalText(4000),
})

export const updateCraneSchema = createCraneSchema

/** Restricting a crane is a safety action, so it always carries a reason (CLAUDE.md rule 2). */
export const restrictCraneSchema = z.object({
  reason: requiredText(500, 'Say why this crane is being restricted.'),
})

export const unrestrictCraneSchema = z.object({
  note: optionalText(500),
})

export const craneFilterSchema = z.object({
  q: z.string().trim().max(160).optional().default(''),
  status: z
    .union([z.literal(''), z.enum(CRANE_STATUSES)])
    .optional()
    .transform((value) => (value === '' || value === undefined ? null : value)),
  type: z
    .union([z.literal(''), z.enum(CRANE_TYPES)])
    .optional()
    .transform((value) => (value === '' || value === undefined ? null : value)),
  customerId: z.string().trim().max(40).optional().default(''),
  siteId: z.string().trim().max(40).optional().default(''),
})

export type CreateCraneInput = z.infer<typeof createCraneSchema>
export type CraneFilter = z.infer<typeof craneFilterSchema>
